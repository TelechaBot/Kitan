export type Lang = keyof typeof MESSAGES;

// Self-contained (no closure) so the Mini App can embed this exact function via toString().
export function selectLang(code: string | undefined, langs: readonly string[]): string {
  const value = (code || "").toLowerCase();
  if (value.indexOf("zh") === 0) {
    return /^zh-(hant|tw|hk|mo)/.test(value) ? "zh-hant" : "zh";
  }
  const base = value.split("-")[0];
  return langs.indexOf(base) >= 0 ? base : "en";
}

export function pickLang(code: string | undefined): Lang {
  return selectLang(code, Object.keys(MESSAGES)) as Lang;
}

// Values are wrapped in Unicode isolates so a Latin group title keeps its
// punctuation in place inside right-to-left text, and vice versa.
export function t(lang: Lang, key: keyof (typeof MESSAGES)["en"], vars: Record<string, string> = {}): string {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => `⁨${vars[name] ?? ""}⁩`);
}
